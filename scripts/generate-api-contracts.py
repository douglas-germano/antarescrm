#!/usr/bin/env python3
"""Generate deterministic OpenAPI and TypeScript contracts; --check fails on drift."""

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
# Generation never imports production credentials or connects to a database.
os.environ['ANTARES_ENV_FILE'] = str(ROOT / 'backend/.env.contract-generation-unused')
os.environ['APP_ENV'] = 'development'
os.environ['TEST_DATABASE_URL'] = 'sqlite:///:memory:'


def typescript_type(schema):
    if '$ref' in schema:
        result = schema['$ref'].rsplit('/', 1)[-1]
    elif 'enum' in schema:
        result = ' | '.join(json.dumps(value, ensure_ascii=False) for value in schema['enum'])
    elif 'oneOf' in schema or 'anyOf' in schema:
        result = ' | '.join(typescript_type(value) for value in schema.get('oneOf', schema.get('anyOf')))
    elif schema.get('type') == 'array':
        result = 'Array<' + typescript_type(schema.get('items', {})) + '>'
    elif schema.get('type') == 'object':
        if 'properties' in schema:
            required = schema.get('required', [])
            result = (
                '{ '
                + ' '.join(
                    json.dumps(key) + ('' if key in required else '?') + ': ' + typescript_type(value) + ';'
                    for key, value in sorted(schema['properties'].items())
                )
                + ' }'
            )
        else:
            extra = schema.get('additionalProperties', {})
            result = 'Record<string, ' + (typescript_type(extra) if isinstance(extra, dict) else 'unknown') + '>'
    else:
        result = {
            'string': 'string',
            'integer': 'number',
            'number': 'number',
            'boolean': 'boolean',
        }.get(schema.get('type'), 'unknown')
    return result + ' | null' if schema.get('nullable') and result != 'unknown' else result


def generate():
    from app import create_app
    from app.contracts import build_spec

    spec = build_spec(create_app('testing'))
    types = '// Generated by scripts/generate-api-contracts.py. Do not edit by hand.\n\n'
    for name, schema in sorted(spec['components']['schemas'].items()):
        types += 'export type ' + name + ' = ' + typescript_type(schema) + ';\n\n'
    return {
        ROOT / 'docs/api/openapi.json': json.dumps(spec, ensure_ascii=False, indent=2, sort_keys=True) + '\n',
        ROOT / 'frontend/src/lib/api.generated.ts': types,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit(
            'API contracts out of date: '
            + ', '.join(stale)
            + '. Run backend/.venv/bin/python scripts/generate-api-contracts.py'
        )
    print('API contracts ' + ('checked.' if args.check else 'generated.'))


if __name__ == '__main__':
    main()
